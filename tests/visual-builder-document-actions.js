const assert=require('node:assert/strict');
const {duplicateSection,canInlineEdit,normaliseInlineText,commitInlineText}=require('../assets/js/visual-builder-document-actions.js');
const source={id:'container-1',type:'section',props:{background:'#f4f8f7',padding:24,mobile:{width:90,padding:12,align:'center'}},children:[{id:'heading-1',type:'heading',props:{text:'Hello',level:2}},{id:'button-1',type:'button',props:{text:'Go',href:'/directory.html'}}]};
const original=JSON.parse(JSON.stringify(source));
let counter=0;
const copy=duplicateSection(source,prefix=>prefix+'-'+(++counter));
assert.notEqual(copy.id,source.id,'container ID is remapped');
assert.equal(copy.children.length,source.children.length,'child count is preserved');
assert.notEqual(copy.children[0].id,source.children[0].id,'heading ID is remapped');
assert.notEqual(copy.children[1].id,source.children[1].id,'button ID is remapped');
assert.deepEqual(copy.props,source.props,'container styling and mobile overrides are preserved');
assert.deepEqual(copy.children.map(x=>x.props),source.children.map(x=>x.props),'child content and settings are preserved');
assert.deepEqual(source,original,'source section is not mutated');
assert.equal(new Set([copy.id,...copy.children.map(x=>x.id)]).size,3,'all cloned IDs are unique');
assert.throws(()=>duplicateSection(null,()=> 'id'),TypeError,'invalid source is rejected');
assert.throws(()=>duplicateSection(source,null),TypeError,'missing ID factory is rejected');
assert.equal(canInlineEdit('heading'),true,'headings support inline editing');
assert.equal(canInlineEdit('paragraph'),true,'paragraphs support inline editing');
assert.equal(canInlineEdit('button'),true,'buttons support inline editing');
assert.equal(canInlineEdit('image'),false,'unsupported elements cannot be edited inline');
assert.equal(normaliseInlineText('First\r\nSecond\u0000!',20),'First\nSecond!','inline text is normalised and control characters are removed');
const paragraph={id:'p1',type:'paragraph',props:{text:'Before'}};
assert.deepEqual(commitInlineText(paragraph,'Line one\r\nLine two'),{ok:true,changed:true,text:'Line one\nLine two'});
assert.equal(paragraph.props.text,'Line one\nLine two','paragraph text is committed as plain text');
const button={id:'b1',type:'button',props:{text:'Continue',href:'/directory.html'}};
const invalidButton=commitInlineText(button,'   ');
assert.equal(invalidButton.ok,false,'button labels cannot be empty');
assert.equal(button.props.text,'Continue','invalid button edit leaves original text unchanged');
const heading={id:'h1',type:'heading',props:{text:'Old'}};
assert.equal(commitInlineText(heading,'x'.repeat(600)).text.length,500,'heading text respects its client-side limit');
assert.equal(heading.props.level,undefined,'inline editing does not alter other block properties');
console.log('Visual Builder duplicate-container and inline-edit tests passed.');