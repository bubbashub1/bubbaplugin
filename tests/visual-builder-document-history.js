const assert=require('node:assert/strict');
const {createHistory}=require('../assets/js/visual-builder-document-actions.js');

const history=createHistory(3);
const first={schema_version:1,sections:[{id:'one',props:{padding:20}}]};
const second={schema_version:1,sections:[{id:'one',props:{padding:28}}]};
const third={schema_version:1,sections:[{id:'one',props:{padding:36}}]};
history.reset();
history.checkpoint(first);
assert.equal(history.canUndo(first),false,'a no-op checkpoint is not undoable');
assert.equal(history.undo(first),null,'undo skips unchanged snapshots');
history.checkpoint(first);
assert.equal(history.canUndo(second),true,'a changed draft can be undone');
const undone=history.undo(second);
assert.deepEqual(undone,first,'undo returns the prior document');
assert.equal(history.canRedo(undone),true,'redo becomes available after undo');
const redone=history.redo(undone);
assert.deepEqual(redone,second,'redo restores the newer document');
history.undo(second);
history.checkpoint(first);
assert.equal(history.canRedo(first),false,'a new edit clears the redo stack');
history.reset();
history.checkpoint(first);
history.checkpoint(second);
history.checkpoint(third);
const fourth={schema_version:1,sections:[{id:'one',props:{padding:44}}]};
history.checkpoint(fourth);
const fifth={schema_version:1,sections:[{id:'one',props:{padding:52}}]};
assert.deepEqual(history.undo(fifth),fourth,'bounded history retains the newest prior state');
assert.deepEqual(history.undo(fourth),third,'bounded history retains the second newest prior state');
assert.deepEqual(history.undo(third),second,'bounded history retains the third newest prior state');
assert.equal(history.undo(second),null,'old history is discarded at the configured limit');
console.log('Visual Builder draft-history tests passed.');
